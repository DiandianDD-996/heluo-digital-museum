import { chromium, expect } from '@playwright/test'

export async function checkUnifiedGuide(base) {
  const model = process.env.LUOSHENG_PREVIEW_MODE === 'model'
  const browser = await chromium.launch({ executablePath: process.env.LUOSHENG_CHROME || undefined })
  try {
    for (const [width, theme] of [[390, 'dark'], [1440, 'light']]) {
      const page = await browser.newPage({ viewport: { width, height: 844 }, hasTouch: width === 390, reducedMotion: 'reduce' })
      try {
        await page.addInitScript(theme => localStorage.setItem('heluo.theme', theme), theme)
        await page.goto(base)
        await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
        const guide = page.getByRole('complementary', { name: '洛笙全站导览' })
        const trigger = guide.getByRole('button', { name: '洛笙导览' })
        const input = guide.getByRole('textbox', { name: '问洛笙' })
        const press = async question => {
          await input.fill(question)
          await input.press('Enter')
        }
        await trigger.click()
        await press('我就五分钟，想看个有意思的')
        await expect(page).toHaveURL(base + '/')
        await guide.getByRole('button', { name: '带我找鼎耳' }).click()
        await expect(page).toHaveURL(base + '/artifacts/heluo-bronze-ding')
        const plate = page.locator('#luosheng-preview')
        await expect(plate.locator('h3')).toBeFocused()
        const resume = plate.getByRole('button', { name: '接着问' })
        await resume.click()
        await expect(input).toBeFocused()
        await press('另一只呢')
        const top = guide.getByRole('button', { name: '看俯视图' })
        await expect(top).toBeVisible()
        await guide.getByText('查看本轮依据').click()
        if (model) await expect(guide.getByRole('button', { name: '鼎耳图版' })).toBeVisible()
        else await expect(guide.getByRole('link', { name: '合成测试出处' })).toHaveAttribute('href', /\/EAR$/)
        await top.click()
        await expect(plate.locator('h3')).toBeFocused()
        await expect(plate.locator('figcaption')).toContainText(/鼎耳|俯视/)
        await resume.click()
        await press('还有一个在哪儿？')
        await expect(top).toBeVisible()
        await input.press('Escape')
        await expect(resume).toBeFocused()
        await plate.getByRole('button', { name: '三足', exact: true }).click()
        await resume.click()
        await press('另一只呢')
        const back = guide.getByRole('button', { name: '看背视图' })
        await expect(back).toBeVisible()
        await guide.getByText('查看本轮依据').click()
        if (model) await expect(guide.getByRole('button', { name: '三足图版' })).toBeVisible()
        else await expect(guide.getByRole('link', { name: '合成测试出处' })).toHaveAttribute('href', /\/FEET$/)
        await expect(plate.getByRole('button', { name: '侧视', exact: true })).toHaveAttribute('aria-pressed', 'true')
        await back.click()
        await expect(plate.getByRole('button', { name: '背视', exact: true })).toHaveAttribute('aria-pressed', 'true')
        await expect(plate.locator('figcaption')).toContainText(/背视|第三/)
        await expect.poll(() => plate.locator('img:visible').evaluate(el => el.naturalWidth)).toBeGreaterThan(0)
        await resume.click()
        await press('你是怎么看出来的？')
        await expect(guide.getByText('查看本轮依据')).toBeVisible()
        await press('明天还有三个人的名额吗？')
        await expect(guide.getByRole('status')).toContainText(/\d{4}-\d{2}-\d{2}.*(?:可选|没有公开可约时段|空位不足)/)
        const slotsReloaded = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/appointment-slots'
          && !new URL(response.url()).search && response.ok())
        await guide.getByRole('link', { name: '看这天的时段' }).click()
        await expect(page).toHaveURL(/\/appointment\?date=\d{4}-\d{2}-\d{2}$/)
        await slotsReloaded
        await expect(page.locator('.appointment-selected-date')).toHaveText(new URL(page.url()).searchParams.get('date'))
        await trigger.click()
        await guide.getByRole('button', { name: '回到青铜鼎 · 三足' }).click()
        await expect(plate.locator('h3')).toBeFocused()
        await expect(plate.getByRole('button', { name: '背视', exact: true })).toHaveAttribute('aria-pressed', 'true')
        await resume.click()
        await press('另一只呢')
        await expect(back).toBeVisible()
        await input.press('Escape')
        await plate.getByRole('link', { name: '去 3D 看三足' }).click()
        await expect(page).toHaveURL(/\/exhibits\/heluo-bronze-ding-3d$/)
        await expect(plate.locator('h3')).toBeFocused()
        await resume.click()
        await press('另一只呢')
        await expect(back).toBeVisible()
        await input.press('Escape')
        await plate.getByRole('link', { name: '回到藏品展签' }).click()
        await expect(plate.locator('h3')).toBeFocused()
        // The model preview has a six-turn fixture limit and a fixed clock. Start a new visitor for the share-link check.
        if (model) await page.context().clearCookies()
        await page.reload()
        await plate.getByRole('button', { name: '问洛笙' }).click()
        await press('另一只呢')
        await expect(guide.getByRole('status')).toContainText('你想看鼎耳、鼎足')
        await expect(guide.getByText('查看本轮依据')).toHaveCount(0)
        await page.goto(base)
        await trigger.click()
        await press('不看鼎，我想找玉器')
        await guide.getByRole('link', { name: /玉璧/ }).click()
        await expect(page).toHaveURL(/\/artifacts\/river-map-jade-bi$/)
        await page.getByRole('button', { name: '问洛笙', exact: true }).click()
        await press('它是什么？')
        await expect(guide.getByRole('status')).toContainText('概念展品')
        console.log(`Unified Luosheng passed ${width}px ${theme} (${model ? 'model adapter' : 'synthetic'})`)
      } finally {
        await page.close()
      }
    }
  } finally {
    await browser.close()
  }
}
